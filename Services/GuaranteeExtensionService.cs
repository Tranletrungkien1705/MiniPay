/// Dịch vụ Quản lý Công văn Đề nghị Gia hạn Thư Bảo lãnh Thanh toán Ngân hàng (Bank Guarantee Extension Dispatch Management).
/// Tương ứng khối Pmt_GrtClaimExt, Pmt_GrtClaimExtDtl và FrmQLCVanGiaHan_PhatHanhBL, FrmTaoCVanGiaHan_PhatHanhBL, CR_ClaimPM trong BizHTC.Payment.
