    /// <summary>
    /// Đọc số tiền thành chữ tiếng Việt tài chính chuẩn.
    /// </summary>
    public static string NumberToVietnameseText(long number)
    {
        if (number == 0) return "Không đồng";
        if (number < 0) return "Âm " + NumberToVietnameseText(-number);

        string[] units = { "", "nghìn", "triệu", "tỷ", "nghìn tỷ", "triệu tỷ" };
        string sNumber = number.ToString();
        var groups = new List<string>();

        while (sNumber.Length > 0)
        {
            int take = Math.Min(3, sNumber.Length);
            groups.Insert(0, sNumber[^take..]);
            sNumber = sNumber[..^take];
        }

        var result = "";
        for (int i = 0; i < groups.Count; i++)
        {
            int groupValue = int.Parse(groups[i]);
            if (groupValue > 0)
            {
                string groupText = ThreeDigitsToText(groupValue, i > 0);
                int unitIndex = groups.Count - 1 - i;
                result += groupText + " " + units[unitIndex] + " ";
            }
        }

        result = result.Trim();
        if (!string.IsNullOrEmpty(result))
        {
            result = char.ToUpper(result[0]) + result[1..] + " đồng chẵn.";
        }
        return result;
    }

    private static string ThreeDigitsToText(int number, bool hasHigherGroup)
    {
        string[] digits = { "không", "một", "hai", "ba", "bốn", "năm", "sáu", "bảy", "tám", "chín" };
        int hundreds = number / 100;
        int tens = (number % 100) / 10;
        int ones = number % 10;

        string result = "";
        if (hundreds > 0 || hasHigherGroup)
        {
            result += digits[hundreds] + " trăm ";
        }

        if (tens > 1)
        {
            result += digits[tens] + " mươi ";
            if (ones == 1) result += "mốt ";
            else if (ones == 5) result += "lăm ";
            else if (ones > 0) result += digits[ones] + " ";
        }
        else if (tens == 1)
        {
            result += "mười ";
            if (ones == 5) result += "lăm ";
            else if (ones > 0) result += digits[ones] + " ";
        }
        else if (tens == 0)
        {
            if (hundreds > 0 || hasHigherGroup)
            {
                if (ones > 0) result += "linh " + digits[ones] + " ";
            }
            else if (ones > 0)
            {
                result += digits[ones] + " ";
            }
        }

        return result.TrimEnd();
    }
