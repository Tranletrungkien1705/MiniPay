    /// <summary>
    /// Báo cáo thống kê tổng hợp dashboard công văn gia hạn bảo lãnh.
    /// </summary>
    public async Task<GuaranteeExtensionSummaryDto> GetSummaryAsync(Guid orgId)
    {
        var dispatches = await db.GuaranteeExtensionDispatches
            .Include(d => d.Details)
            .Where(d => d.OrgId == orgId)
            .ToListAsync();

        int totalCount = dispatches.Count;
        int draftCount = dispatches.Count(d => d.Status == GuaranteeExtensionStatus.Draft);
        int signedCount = dispatches.Count(d => d.Status == GuaranteeExtensionStatus.Signed);
        int acceptedCount = dispatches.Count(d => d.Status == GuaranteeExtensionStatus.BankAccepted);
        int rejectedCount = dispatches.Count(d => d.Status == GuaranteeExtensionStatus.BankRejected);
        int cancelledCount = dispatches.Count(d => d.Status == GuaranteeExtensionStatus.Cancelled);

        long totalGuaranteeAmount = dispatches.Where(d => d.Status != GuaranteeExtensionStatus.Cancelled).Sum(d => d.TotalAmount);
        long acceptedGuaranteeAmount = dispatches.Where(d => d.Status == GuaranteeExtensionStatus.BankAccepted).Sum(d => d.TotalAmount);

        int totalVehicles = dispatches.Where(d => d.Status != GuaranteeExtensionStatus.Cancelled).Sum(d => d.TotalCarCount);
        int vehiclesNotDelivered = dispatches.Where(d => d.Status != GuaranteeExtensionStatus.Cancelled).Sum(d => d.TotalCarsNotDelivered);

        var byBank = dispatches
            .Where(d => d.Status != GuaranteeExtensionStatus.Cancelled)
            .GroupBy(d => d.BankCode)
            .Select(g => new BankGuaranteeExtSummaryItem(
                BankCode: g.Key,
                BankName: g.First().BankName,
                DispatchCount: g.Count(),
                CarCount: g.Sum(x => x.TotalCarCount),
                TotalAmount: g.Sum(x => x.TotalAmount),
                AcceptedCount: g.Count(x => x.Status == GuaranteeExtensionStatus.BankAccepted)
            ))
            .ToList();

        return new GuaranteeExtensionSummaryDto(
            TotalDispatches: totalCount,
            DraftCount: draftCount,
            SignedCount: signedCount,
            AcceptedCount: acceptedCount,
            RejectedCount: rejectedCount,
            CancelledCount: cancelledCount,
            TotalGuaranteeAmount: totalGuaranteeAmount,
            AcceptedGuaranteeAmount: acceptedGuaranteeAmount,
            TotalVehicles: totalVehicles,
            VehiclesNotDelivered: vehiclesNotDelivered,
            ByBank: byBank
        );
    }

