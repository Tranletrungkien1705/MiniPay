    /// <summary>
    /// Lập công văn đề nghị gia hạn bảo lãnh mới (Pmt_GrtClaimExt_Save_New20200522 / FrmTaoCVanGiaHan_PhatHanhBL).
    /// </summary>
    public async Task<GuaranteeExtensionDispatch> CreateDispatchAsync(
        Guid orgId,
        string? dispatchNo,
        string dealerCode,
        string? dealerName,
        string bankCode,
        string? bankName,
        string? bankCodeMonitor,
        string flagIsHTC,
        int numberOfDaysExt,
        string? remark,
        string? createdBy,
        List<GuaranteeExtensionItemInputDto> items)
    {
        if (string.IsNullOrWhiteSpace(dealerCode))
            throw new ArgumentException("Mã đại lý (DealerCode) không được để trống.");
        if (string.IsNullOrWhiteSpace(bankCode))
            throw new ArgumentException("Mã ngân hàng phát hành bảo lãnh (BankCode) không được để trống.");
        if (numberOfDaysExt <= 0)
            throw new ArgumentException("Số ngày đề nghị gia hạn bảo lãnh phải > 0 ngày.");
        if (items == null || items.Count == 0)
            throw new ArgumentException("Công văn gia hạn bảo lãnh cần ít nhất 1 dòng xe.");

        var finalNo = string.IsNullOrWhiteSpace(dispatchNo)
            ? $"CVGH-{DateTime.Now:yyyyMMdd}-{Random.Shared.Next(100, 999)}"
            : dispatchNo.Trim().ToUpper();

        var exists = await db.GuaranteeExtensionDispatches.AnyAsync(d => d.OrgId == orgId && d.DispatchNo == finalNo);
        if (exists)
            throw new InvalidOperationException($"Số công văn đề nghị gia hạn '{finalNo}' đã tồn tại trên hệ thống.");

        var vinSet = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var it in items)
        {
            if (string.IsNullOrWhiteSpace(it.VIN))
                throw new ArgumentException("Số khung xe (VIN) không được để trống.");
            if (!vinSet.Add(it.VIN.Trim().ToUpper()))
                throw new ArgumentException($"Số khung VIN '{it.VIN}' bị trùng lặp trong cùng công văn.");
        }

        var details = new List<GuaranteeExtensionDetail>();
        foreach (var item in items)
        {
            var detail = BuildDetailItem(orgId, item, numberOfDaysExt);
            details.Add(detail);
        }

        var dispatch = new GuaranteeExtensionDispatch
        {
            OrgId = orgId,
            DispatchNo = finalNo,
            DealerCode = dealerCode.Trim().ToUpper(),
            DealerName = string.IsNullOrWhiteSpace(dealerName) ? dealerCode.Trim().ToUpper() : dealerName.Trim(),
            BankCode = bankCode.Trim().ToUpper(),
            BankName = string.IsNullOrWhiteSpace(bankName) ? ResolveBankName(bankCode) : bankName.Trim(),
            BankCodeMonitor = bankCodeMonitor?.Trim().ToUpper(),
            FlagIsHTC = string.IsNullOrWhiteSpace(flagIsHTC) ? "1" : flagIsHTC.Trim(),
            NumberOfDaysExt = numberOfDaysExt,
            TotalCarCount = details.Count,
            TotalAmount = details.Sum(d => d.GrtValue),
            TotalCarsNotDelivered = details.Count(d => !d.IsDelivered),
            TotalCarsDelivered = details.Count(d => d.IsDelivered),
            Status = GuaranteeExtensionStatus.Draft,
            SignCAStatus = ExtensionSignCAStatus.Pending,
            Remark = remark?.Trim(),
            CreatedBy = string.IsNullOrWhiteSpace(createdBy) ? "ChuyenVienTinDungHTC" : createdBy.Trim(),
            CreatedAt = DateTime.Now,
            Details = details
        };

        db.GuaranteeExtensionDispatches.Add(dispatch);
        await db.SaveChangesAsync();
        return dispatch;
    }

    /// <summary>
    /// Tự động quét các bảo lãnh ngân hàng sắp hết hạn và tạo công văn gia hạn (Pmt_GrtClaimExt_GenAuto_New20201210).
    /// </summary>
    public async Task<List<GuaranteeExtensionDispatch>> AutoGenerateDispatchesAsync(
        Guid orgId,
        int withinDays = 15,
        int numberOfDaysExt = 30,
        string flagIsHTC = "1",
        string? remark = "Hệ thống tự động sinh công văn gia hạn bảo lãnh định kỳ",
        string? createdBy = "AutoScheduleService")
    {
        var targetDate = DateTime.Today.AddDays(withinDays);

        // Lấy danh sách các bảo lãnh đang có hiệu lực và sắp hết hạn
        var activeGuarantees = await db.Guarantees
            .Include(g => g.Details)
            .Where(g => g.OrgId == orgId &&
                        g.Status == GuaranteeStatus.Active &&
                        g.DateExpired <= targetDate)
            .ToListAsync();

        if (activeGuarantees.Count == 0)
            return [];

        // Nhóm theo Ngân hàng và Đại lý
        var grouped = activeGuarantees.GroupBy(g => new { g.BankCode, g.PartnerCode });
        var createdList = new List<GuaranteeExtensionDispatch>();

        foreach (var group in grouped)
        {
            var bankCode = group.Key.BankCode;
            var dealerCode = group.Key.PartnerCode;
            var firstGrt = group.First();

            var finalNo = $"CVGH-AUTO-{DateTime.Now:yyyyMMdd}-{Random.Shared.Next(100, 999)}";

            var items = new List<GuaranteeExtensionDetail>();
            foreach (var grt in group)
            {
                foreach (var dtl in grt.Details.Where(d => d.Status == GuaranteeDetailStatus.Active))
                {
                    var expDate = grt.DateExpired;
                    var newExpDate = expDate.AddDays(numberOfDaysExt);

                    items.Add(new GuaranteeExtensionDetail
                    {
                        OrgId = orgId,
                        CarId = dtl.ItemRefNo,
                        VIN = !string.IsNullOrWhiteSpace(dtl.ItemRefNo) && dtl.ItemRefNo.Length >= 10 ? dtl.ItemRefNo : $"KMHCT81EPHU{Random.Shared.Next(100000, 999999)}",
                        ModelCode = "SANTAFE-CALLI",
                        ModelName = !string.IsNullOrWhiteSpace(dtl.Description) ? dtl.Description : "Hyundai Santa Fe Calligraphy",
                        SpecCode = "STD",
                        SpecDescription = "Bản tiêu chuẩn phân phối HTC",
                        ColorName = "Trắng Tinh Khôi",
                        SOCode = grt.ContractNo,
                        DlrCtrNo = grt.ContractNo,
                        GuaranteeNo = grt.GuaranteeNo,
                        BankGuaranteeNo = grt.BankGuaranteeNo,
                        GrtDateStart = grt.DateOpen,
                        GrtDateExpired = expDate,
                        ExtendedDate = newExpDate,
                        GrtValue = dtl.GuaranteeValue > 0 ? dtl.GuaranteeValue : 1_000_000_000,
                        UnitPrice = dtl.OrderAmount > 0 ? dtl.OrderAmount : 1_250_000_000,
                        IsDelivered = false,
                        Status = GuaranteeExtensionDetailStatus.Pending,
                        Remark = "Quét tự động từ hệ thống bảo lãnh HTC"
                    });
                }
            }

            if (items.Count == 0) continue;

            var dispatch = new GuaranteeExtensionDispatch
            {
                OrgId = orgId,
                DispatchNo = finalNo,
                DealerCode = dealerCode,
                DealerName = firstGrt.PartnerName ?? dealerCode,
                BankCode = bankCode,
                BankName = firstGrt.BankName ?? ResolveBankName(bankCode),
                FlagIsHTC = flagIsHTC,
                NumberOfDaysExt = numberOfDaysExt,
                TotalCarCount = items.Count,
                TotalAmount = items.Sum(d => d.GrtValue),
                TotalCarsNotDelivered = items.Count(d => !d.IsDelivered),
                TotalCarsDelivered = items.Count(d => d.IsDelivered),
                Status = GuaranteeExtensionStatus.Draft,
                SignCAStatus = ExtensionSignCAStatus.Pending,
                Remark = remark,
                CreatedBy = createdBy,
                CreatedAt = DateTime.Now,
                Details = items
            };

            db.GuaranteeExtensionDispatches.Add(dispatch);
            createdList.Add(dispatch);
        }

        await db.SaveChangesAsync();
        return createdList;
    }

    /// <summary>
    /// Ký số điện tử CA và phát hành công văn (Pmt_GrtClaimExt_SignAndSendEmail / FrmQLCVanGiaHan_PhatHanhBL.btnKyDienTu).
    /// </summary>
    public async Task<GuaranteeExtensionDispatch?> SignCAAsync(long id, Guid orgId, string? signerName, string? filePath)
    {
        var dispatch = await db.GuaranteeExtensionDispatches
            .Include(d => d.Details)
            .FirstOrDefaultAsync(d => d.Id == id && d.OrgId == orgId);

        if (dispatch == null) return null;

        if (dispatch.Status != GuaranteeExtensionStatus.Draft && dispatch.Status != GuaranteeExtensionStatus.PendingSign)
            throw new InvalidOperationException($"Chỉ có thể ký số công văn ở trạng thái Mới tạo (Draft) hoặc Chờ ký (PendingSign). Trạng thái hiện tại: {dispatch.Status}.");

        dispatch.SignCAStatus = ExtensionSignCAStatus.Signed;
        dispatch.Status = GuaranteeExtensionStatus.Signed;
        dispatch.SignedBy = string.IsNullOrWhiteSpace(signerName) ? "NguyenVanHieu_TongGiamDoc_HTV" : signerName.Trim();
        dispatch.SignedAt = DateTime.Now;
        dispatch.CertThumbprint = Guid.NewGuid().ToString("N").ToUpper()[..16];
        dispatch.FilePath = string.IsNullOrWhiteSpace(filePath) ? $"/documents/extension/{dispatch.DispatchNo}-Signed.pdf" : filePath.Trim();

        foreach (var dtl in dispatch.Details)
        {
            dtl.Status = GuaranteeExtensionDetailStatus.Active;
        }

        await db.SaveChangesAsync();
        return dispatch;
    }

    /// <summary>
    /// Ghi nhận ngân hàng phát hành chấp thuận gia hạn thời hạn Thư bảo lãnh và đồng bộ cập nhật ngày hết hạn mới.
    /// </summary>
    public async Task<GuaranteeExtensionDispatch?> BankAcceptAsync(long id, Guid orgId, string bankResponseRef, string? note)
    {
        if (string.IsNullOrWhiteSpace(bankResponseRef))
            throw new ArgumentException("Số công văn / thông báo chấp thuận của ngân hàng không được để trống.");

        var dispatch = await db.GuaranteeExtensionDispatches
            .Include(d => d.Details)
            .FirstOrDefaultAsync(d => d.Id == id && d.OrgId == orgId);

        if (dispatch == null) return null;

        if (dispatch.Status != GuaranteeExtensionStatus.Signed)
            throw new InvalidOperationException($"Chỉ có thể ghi nhận ngân hàng chấp thuận khi công văn đã được ký số (Signed). Trạng thái hiện tại: {dispatch.Status}.");

        dispatch.Status = GuaranteeExtensionStatus.BankAccepted;
        dispatch.BankResponseRef = bankResponseRef.Trim();
        dispatch.BankAcceptedAt = DateTime.Now;
        if (!string.IsNullOrWhiteSpace(note))
            dispatch.Remark = string.IsNullOrWhiteSpace(dispatch.Remark) ? note.Trim() : $"{dispatch.Remark} | {note.Trim()}";

        foreach (var dtl in dispatch.Details)
        {
            dtl.Status = GuaranteeExtensionDetailStatus.BankAccepted;

            // Đồng bộ cập nhật ngày hết hạn mới cho Thư bảo lãnh gốc trên hệ thống
            if (!string.IsNullOrWhiteSpace(dtl.BankGuaranteeNo))
            {
                var relatedGuarantees = await db.Guarantees
                    .Where(g => g.OrgId == orgId && g.BankGuaranteeNo == dtl.BankGuaranteeNo)
                    .ToListAsync();

                foreach (var g in relatedGuarantees)
                {
                    if (g.DateExpired < dtl.ExtendedDate)
                    {
                        g.DateExpired = dtl.ExtendedDate;
                        g.DateEnd = dtl.ExtendedDate;
                    }
                }
            }
        }

        await db.SaveChangesAsync();
        return dispatch;
    }

    /// <summary>
    /// Ghi nhận ngân hàng từ chối gia hạn bảo lãnh kèm lý do.
    /// </summary>
    public async Task<GuaranteeExtensionDispatch?> BankRejectAsync(long id, Guid orgId, string reason)
    {
        if (string.IsNullOrWhiteSpace(reason))
            throw new ArgumentException("Lý do ngân hàng từ chối gia hạn không được để trống.");

        var dispatch = await db.GuaranteeExtensionDispatches
            .Include(d => d.Details)
            .FirstOrDefaultAsync(d => d.Id == id && d.OrgId == orgId);

        if (dispatch == null) return null;

        if (dispatch.Status != GuaranteeExtensionStatus.Signed)
            throw new InvalidOperationException($"Chỉ có thể ghi nhận từ chối khi công văn đã được ký và gửi ngân hàng (Signed). Trạng thái hiện tại: {dispatch.Status}.");

        dispatch.Status = GuaranteeExtensionStatus.BankRejected;
        dispatch.BankRejectReason = reason.Trim();

        foreach (var dtl in dispatch.Details)
        {
            dtl.Status = GuaranteeExtensionDetailStatus.BankRejected;
        }

        await db.SaveChangesAsync();
        return dispatch;
    }

    /// <summary>
    /// Hủy công văn gia hạn bảo lãnh (Pmt_GrtClaimExt_Cancel / FrmQLCVanGiaHan_PhatHanhBL.btnDelete).
    /// </summary>
    public async Task<GuaranteeExtensionDispatch?> CancelDispatchAsync(long id, Guid orgId, string? reason)
    {
        var dispatch = await db.GuaranteeExtensionDispatches
            .Include(d => d.Details)
            .FirstOrDefaultAsync(d => d.Id == id && d.OrgId == orgId);

        if (dispatch == null) return null;

        if (dispatch.Status == GuaranteeExtensionStatus.BankAccepted)
            throw new InvalidOperationException("Không thể hủy công văn khi ngân hàng đã chính thức chấp thuận gia hạn.");

        dispatch.Status = GuaranteeExtensionStatus.Cancelled;
        dispatch.CancelledAt = DateTime.Now;
        if (!string.IsNullOrWhiteSpace(reason))
            dispatch.Remark = string.IsNullOrWhiteSpace(dispatch.Remark) ? reason.Trim() : $"{dispatch.Remark} | Hủy: {reason.Trim()}";

        foreach (var dtl in dispatch.Details)
        {
            dtl.Status = GuaranteeExtensionDetailStatus.Cancelled;
        }

        await db.SaveChangesAsync();
        return dispatch;
    }

    /// <summary>
    /// Bổ sung xe vào công văn đang ở trạng thái Draft.
    /// </summary>
    public async Task<GuaranteeExtensionDispatch> AddVehiclesAsync(long id, Guid orgId, List<GuaranteeExtensionItemInputDto> items)
    {
        if (items == null || items.Count == 0)
            throw new ArgumentException("Cần danh sách xe để bổ sung vào công văn.");

        var dispatch = await db.GuaranteeExtensionDispatches
            .Include(d => d.Details)
            .FirstOrDefaultAsync(d => d.Id == id && d.OrgId == orgId)
            ?? throw new InvalidOperationException($"Không tìm thấy công văn #{id}.");

        if (dispatch.Status != GuaranteeExtensionStatus.Draft)
            throw new InvalidOperationException("Chỉ có thể bổ sung xe khi công văn ở trạng thái Mới tạo (Draft).");

        var existingVins = new HashSet<string>(dispatch.Details.Select(d => d.VIN), StringComparer.OrdinalIgnoreCase);

        foreach (var item in items)
        {
            if (string.IsNullOrWhiteSpace(item.VIN)) continue;
            var vinUpper = item.VIN.Trim().ToUpper();
            if (existingVins.Contains(vinUpper)) continue;
            existingVins.Add(vinUpper);

            var detail = BuildDetailItem(orgId, item, dispatch.NumberOfDaysExt);
            dispatch.Details.Add(detail);
        }

        dispatch.TotalCarCount = dispatch.Details.Count;
        dispatch.TotalAmount = dispatch.Details.Sum(d => d.GrtValue);
        dispatch.TotalCarsNotDelivered = dispatch.Details.Count(d => !d.IsDelivered);
        dispatch.TotalCarsDelivered = dispatch.Details.Count(d => d.IsDelivered);

        await db.SaveChangesAsync();
        return dispatch;
    }

    /// <summary>
    /// Xóa 1 xe khỏi công văn đang ở trạng thái Draft.
    /// </summary>
    public async Task<GuaranteeExtensionDispatch> RemoveVehicleAsync(long id, long detailId, Guid orgId)
    {
        var dispatch = await db.GuaranteeExtensionDispatches
            .Include(d => d.Details)
            .FirstOrDefaultAsync(d => d.Id == id && d.OrgId == orgId)
            ?? throw new InvalidOperationException($"Không tìm thấy công văn #{id}.");

        if (dispatch.Status != GuaranteeExtensionStatus.Draft)
            throw new InvalidOperationException("Chỉ có thể xóa xe khi công văn ở trạng thái Mới tạo (Draft).");

        var detail = dispatch.Details.FirstOrDefault(d => d.Id == detailId)
            ?? throw new InvalidOperationException($"Không tìm thấy dòng xe #{detailId} trong công văn.");

        dispatch.Details.Remove(detail);
        db.GuaranteeExtensionDetails.Remove(detail);

        dispatch.TotalCarCount = dispatch.Details.Count;
        dispatch.TotalAmount = dispatch.Details.Sum(d => d.GrtValue);
        dispatch.TotalCarsNotDelivered = dispatch.Details.Count(d => !d.IsDelivered);
        dispatch.TotalCarsDelivered = dispatch.Details.Count(d => d.IsDelivered);

        await db.SaveChangesAsync();
        return dispatch;
    }

    /// <summary>
    /// Xóa nháp công văn gia hạn chưa ký số.
    /// </summary>
    public async Task DeleteDraftAsync(long id, Guid orgId)
    {
        var dispatch = await db.GuaranteeExtensionDispatches
            .Include(d => d.Details)
            .FirstOrDefaultAsync(d => d.Id == id && d.OrgId == orgId)
            ?? throw new InvalidOperationException($"Không tìm thấy công văn #{id}.");

        if (dispatch.Status != GuaranteeExtensionStatus.Draft && dispatch.Status != GuaranteeExtensionStatus.Cancelled)
            throw new InvalidOperationException("Chỉ có thể xóa công văn ở trạng thái Mới tạo (Draft) hoặc Đã hủy (Cancelled).");

        if (dispatch.SignCAStatus == ExtensionSignCAStatus.Signed)
            throw new InvalidOperationException("Không thể xóa công văn đã được ký số điện tử CA.");

        db.GuaranteeExtensionDetails.RemoveRange(dispatch.Details);
        db.GuaranteeExtensionDispatches.Remove(dispatch);
        await db.SaveChangesAsync();
    }

    /// <summary>
    /// Lấy danh sách công văn kèm bộ lọc (Pmt_GrtClaimExt_Get).
    /// </summary>
    public async Task<List<GuaranteeExtensionDispatch>> GetDispatchesAsync(
        Guid orgId,
        string? dealerCode = null,
        string? bankCode = null,
        string? status = null,
        string? flagIsHTC = null,
        string? vin = null)
    {
        var query = db.GuaranteeExtensionDispatches
            .Include(d => d.Details)
            .Where(d => d.OrgId == orgId)
            .AsQueryable();

        if (!string.IsNullOrWhiteSpace(dealerCode))
            query = query.Where(d => d.DealerCode == dealerCode.Trim().ToUpper());

        if (!string.IsNullOrWhiteSpace(bankCode))
            query = query.Where(d => d.BankCode == bankCode.Trim().ToUpper());

        if (!string.IsNullOrWhiteSpace(status) && Enum.TryParse<GuaranteeExtensionStatus>(status, true, out var st))
            query = query.Where(d => d.Status == st);

        if (!string.IsNullOrWhiteSpace(flagIsHTC))
            query = query.Where(d => d.FlagIsHTC == flagIsHTC.Trim());

        if (!string.IsNullOrWhiteSpace(vin))
        {
            var vinUpper = vin.Trim().ToUpper();
            query = query.Where(d => d.Details.Any(dt => dt.VIN.Contains(vinUpper)));
        }

        return await query.OrderByDescending(d => d.CreatedAt).ToListAsync();
    }

